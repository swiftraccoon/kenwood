//! Extraction failure type shared by every phase of the extractor.

use std::path::PathBuf;

/// Raised when the expected serializer shape cannot be extracted.
///
/// The extractor is deliberately narrow: any deviation from the reviewed
/// decompilation shape fails extraction with a message describing the
/// unexpected input instead of silently omitting a writer.
#[derive(Debug, thiserror::Error)]
pub enum ExtractError {
    /// Input violates the parser or extraction request's contract.
    #[error("invalid input: {message}")]
    InvalidInput {
        /// Input location and rejected value.
        message: String,
    },
    /// Serializer structure differs from a supported layout.
    #[error("{message}")]
    UnsupportedLayout {
        /// Class, method, line or relationship that failed verification.
        message: String,
    },
    /// An input or output filesystem operation failed.
    #[error("cannot {operation} {}: {source}", path.display())]
    Io {
        /// Filesystem operation.
        operation: &'static str,
        /// Path involved in the operation.
        path: PathBuf,
        /// Original operating-system error.
        #[source]
        source: std::io::Error,
    },
    /// JSON decoding or encoding failed.
    #[error("cannot {operation} manifest: {source}")]
    Json {
        /// Whether parsing or serialization failed.
        operation: &'static str,
        /// Original JSON error including its line and column.
        #[source]
        source: serde_json::Error,
    },
    /// A parser or decoder failed while processing a named input.
    #[error("{context}: {source}")]
    Source {
        /// Source location and operation.
        context: String,
        /// Original parser or decoding error.
        #[source]
        source: Box<dyn std::error::Error + Send + Sync>,
    },
    /// Decompilation completed with an unsuccessful process status.
    #[error("ILSpy decompilation failed with exit code {code:?}")]
    Subprocess {
        /// Exit code, or `None` when terminated by a signal.
        code: Option<i32>,
    },
    /// Generated bytes differ from the checked destination.
    #[error("generated output differs: {}", path.display())]
    GenerationMismatch {
        /// Destination whose bytes differ.
        path: PathBuf,
    },
    /// Publication stopped after zero or more complete atomic replacements.
    #[error("cannot publish {} after replacing {published:?}: {source}", pending.display())]
    Publication {
        /// Destinations already replaced, in publication order.
        published: Vec<PathBuf>,
        /// Destination whose replacement failed.
        pending: PathBuf,
        /// Original replacement error; each prior replacement is complete.
        #[source]
        source: std::io::Error,
    },
}

impl ExtractError {
    /// Describe an unsupported serializer layout with its source context.
    pub fn new(message: impl Into<String>) -> Self {
        Self::UnsupportedLayout {
            message: message.into(),
        }
    }

    pub(crate) fn io(
        operation: &'static str,
        path: &std::path::Path,
        source: std::io::Error,
    ) -> Self {
        Self::Io {
            operation,
            path: path.to_owned(),
            source,
        }
    }

    pub(crate) fn source(
        context: impl Into<String>,
        source: impl std::error::Error + Send + Sync + 'static,
    ) -> Self {
        Self::Source {
            context: context.into(),
            source: Box::new(source),
        }
    }
}

/// Extraction result alias used throughout the crate.
pub type Result<T> = std::result::Result<T, ExtractError>;

/// Describe an unsupported serializer relationship with formatted source context.
macro_rules! extract_error {
    ($($arg:tt)*) => {
        $crate::error::ExtractError::new(format!($($arg)*))
    };
}
pub(crate) use extract_error;
